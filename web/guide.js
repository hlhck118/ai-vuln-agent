  /**
   * 行内富文本：把 `**加粗**` 拆成 <strong> 节点，其余原样成文本节点。
   *
   * 正文数据里一直写着 `**…**`，而块渲染走的是 el() → textContent，于是那些星号
   * **原样显示在页面上**——说明书里满屏星号比不加粗更糟。app.js 的 renderInline
   * 做的是同一件事，这里只取"加粗"一种标记：页内说明书的正文由本文件静态持有，
   * 不需要一个完整的 Markdown 解析器。
   *
   * 按 `**` 切分后奇数段即被夹住的那一段（等价于逐标记取反），所以未配对的尾巴
   * 不会吞掉正文，只会少一次加粗。返回 DocumentFragment，调用方仍然只 append，
   * 不拼 HTML 字符串。
   */
  function rich(text) {
    const frag = document.createDocumentFragment();
    String(text == null ? '' : text).split('**').forEach((part, index) => {
      if (!part) return;
      frag.append(index % 2 === 1 ? el('strong', null, part) : document.createTextNode(part));
    });
    return frag;
  }

  /** 建元素并把 rich() 的结果塞进去（元素本身仍走 el，不拼 HTML）。 */
  function withRich(tag, className, text) {
    const node = el(tag, className);
    node.append(rich(text));
    return node;
  }

  function buildBlock(block) {
    if (block.t === 'p') return withRich('p', 'guide-p', block.text);
    if (block.t === 'note') return withRich('p', 'notice ' + (block.kind || ''), block.text);
    if (block.t === 'cmd') return buildCmd(block);
    if (block.t === 'table') return buildTable(block);
    if (block.t === 'list' || block.t === 'steps') {
      const list = el(block.t === 'steps' ? 'ol' : 'ul', block.t === 'steps' ? 'guide-steps' : 'guide-list');
      (block.items || []).forEach((item) => list.append(withRich('li', null, item)));
      return list;
    }
    return withRich('p', 'guide-p', block.text || '');
  }

  /** 搜索用正文：把一章里所有可见文字拼起来，表格与命令也要能被搜到。 */
  function searchTextOf(section) {
    const parts = [section.title, section.summary || '', section.where || ''];
    section.blocks.forEach((block) => {
      if (block.text) parts.push(block.text);
      if (block.label) parts.push(block.label);
      if (block.items) parts.push(block.items.join(' '));
      if (block.head) parts.push(block.head.join(' '));
      if (block.rows) block.rows.forEach((row) => parts.push(row.join(' ')));
    });
    return parts.join(' ').toLowerCase();
  }

