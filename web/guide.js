  function metaText(keyword, hits) {
    if (keyword) return `匹配 ${hits} / ${SECTIONS.length} 章` + (hits ? '' : '，换个关键词试试');
    return `共 ${SECTIONS.length} 章 · 与仓库里的 使用手册.md 同步`;
  }

  function applyFilter(raw) {
    const keyword = String(raw || '').trim().toLowerCase();
    let hits = 0;
    SECTIONS.forEach((section) => {
      const hit = !keyword || searchTextOf(section).includes(keyword);
      const node = rendered.get(section.id);
      if (node) node.classList.toggle('hidden', !hit);
      const item = tocItems.get(section.id);
      if (item) item.classList.toggle('hidden', !hit);
      if (hit) hits += 1;
    });
    dom.meta.textContent = metaText(keyword, hits);
    dom.reset.classList.toggle('hidden', !keyword);
    if (dom.content) dom.content.scrollTop = 0;
    scheduleSync();
  }

