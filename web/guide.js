  function syncCurrent() {
    view.frame = 0;
    if (!dom.content) return;
    const base = dom.content.getBoundingClientRect().top + 12;
    let current = null;
    rendered.forEach((node, id) => {
      if (node.classList.contains('hidden')) return;
      if (node.getBoundingClientRect().top <= base) current = id;   // 迭代顺序即章节顺序
    });
    tocItems.forEach((item, id) => item.classList.toggle('on', id === current));
  }

  function scheduleSync() {
    if (view.frame) return;
    view.frame = window.requestAnimationFrame(syncCurrent);
  }

